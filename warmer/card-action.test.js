import test from 'node:test';
import assert from 'node:assert/strict';
import{cardAction}from'./card-action.js';
const base={tCode:0,maxRain:5,feels:18,nowTemp:18,wind:10,band:'DAY',slots:[],uvIndex:2};
test('empty input gives empty text',()=>assert.equal(cardAction(null),''));
test('thunder beats everything',()=>assert.equal(cardAction({...base,tCode:95,maxRain:90}),'Stay in if you can.'));
test('rain chance >=60 asks for umbrella',()=>assert.equal(cardAction({...base,maxRain:65}),'Take an umbrella.'));
test('freezing feels-like',()=>assert.equal(cardAction({...base,feels:-3}),'Wear your warmest coat.'));
test('cold',()=>assert.equal(cardAction({...base,feels:5}),'Pack your jacket.'));
test('cool',()=>assert.equal(cardAction({...base,feels:12}),'Bring a light jacket.'));
test('evening drop in daytime',()=>assert.equal(cardAction({...base,feels:16,slots:[{label:'evening',temp:9}]}),'Jacket for tonight.'));
test('hot',()=>assert.equal(cardAction({...base,feels:30}),'Stay cool, drink water.'));
test('mild default',()=>assert.equal(cardAction({...base,feels:18}),'Nothing special needed.'));
test('wind',()=>assert.equal(cardAction({...base,wind:50}),'Hold onto your hat.'));
